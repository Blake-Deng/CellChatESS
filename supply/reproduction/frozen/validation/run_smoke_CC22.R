args<-commandArgs(TRUE)
stopifnot(length(args)==4L)
.libPaths(c(args[3],args[4],.libPaths()))
suppressPackageStartupMessages({library(CellChat);library(CellChatESS)})
future::plan('sequential')
stopifnot(as.character(packageVersion('CellChat'))=='2.2.0.9001',as.character(packageVersion('CellChatESS'))=='0.2.2')
input<-args[1];dir.create(args[2],recursive=TRUE,showWarnings=FALSE)
if(file.exists(file.path(args[2],'checks.tsv')))stop('Refusing to overwrite smoke checks')
x<-readRDS(input);x@idents<-droplevels(x@idents)
settings<-list(type='triMean',raw.use=TRUE,population.size=FALSE,nboot=100L,seed.use=1L,Kh=0.5,n=1)
y<-do.call(CellChat::computeCommunProb,c(list(object=x),settings))
z<-do.call(CellChatESS::computeCommunProbESS,c(list(object=x,algorithm='ess',threads=1L),settings))
d<-do.call(CellChatESS::computeCommunProbESS,c(list(object=x,algorithm='dense'),settings))
checks<-list()
compare<-function(a,b,label,exact=FALSE) {
 stopifnot(identical(dim(a),dim(b)),identical(dimnames(a),dimnames(b)),all(is.finite(a)),all(is.finite(b)))
 row<-data.frame(check=label,elements=length(a),max_absolute_difference=if(length(a))max(abs(a-b))else 0,different_elements=sum(a!=b),elementwise_exact=all(a==b))
 checks[[length(checks)+1L]]<<-row
 if(exact)stopifnot(row$elementwise_exact)
 else stopifnot(row$max_absolute_difference<=1e-12)
}
compare(y@net$prob,z@net$prob,'prob_original_vs_ess')
compare(y@net$pval,z@net$pval,'pval_original_vs_ess',TRUE)
compare(y@net$prob,d@net$prob,'prob_original_vs_dense')
compare(y@net$pval,d@net$pval,'pval_original_vs_dense',TRUE)
y<-CellChat::filterCommunication(y,min.cells=10)
z<-CellChat::filterCommunication(z,min.cells=10)
yp<-CellChat::computeCommunProbPathway(y);zp<-CellChatESS::computeCommunProbPathwayESS(z)
compare(yp@netP$prob,zp@netP$prob,'pathway_probability')
ya<-CellChat::aggregateNet(yp);za<-CellChatESS::aggregateNetESS(zp)
compare(ya@net$count,za@net$count,'aggregate_count',TRUE)
compare(ya@net$weight,za@net$weight,'aggregate_weight')
# Storage invariance is tested against the same candidate and same input.
xd<-x;xd@data.signaling<-as.matrix(x@data.signaling)
zd<-do.call(CellChatESS::computeCommunProbESS,c(list(object=xd,threads=1L),settings))
compare(zd@net$prob,z@net$prob,'sparse_vs_dense_probability',TRUE)
compare(zd@net$pval,z@net$pval,'sparse_vs_dense_pvalue',TRUE)
write.table(do.call(rbind,checks),file.path(args[2],'checks.tsv'),sep='\t',row.names=FALSE,quote=TRUE)
writeLines(capture.output(sessionInfo()),file.path(args[2],'sessionInfo.txt'))
write.table(data.frame(cells=ncol(x@data.signaling),signaling_genes=nrow(x@data.signaling),K=nlevels(x@idents),nLR=nrow(x@LR$LRsig),nboot=100,seed=1,CellChat=as.character(packageVersion('CellChat')),CellChatESS=as.character(packageVersion('CellChatESS'))),file.path(args[2],'input_and_versions.tsv'),sep='\t',row.names=FALSE,quote=TRUE)
cat('ALL PBMC SMOKE CHECKS PASSED\n')
